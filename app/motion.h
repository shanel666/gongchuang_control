#ifndef __MOTION_H
#define __MOTION_H

#include "stm32f10x.h"

/* ============================================================================
 * 运动控制（"走一段 / 到某点"这一层）
 * ----------------------------------------------------------------------------
 * 位置比 motor.c 高一层：motor.c 负责"发一帧、等到位"，
 * 这里负责"按场地坐标走、按朝向对齐、走到目标点"。
 *
 * 原来这几个函数在 main.c 里，逻辑未改，只改了链接性（static → 全局）。
 * ========================================================================== */

/* 等四个电机到位的轮数上限（有界，避免驱动器掉线时整条路线卡死）。
 * 实际用法见 wait_motors()。 */
#define MOVE_TIMEOUT_ROUNDS 500u

/* 车头当前朝向（绝对方向编号）：1=北 2=西 3=南 4=东。
 * 原来是 main.c 的文件级 static，因为 translation() 和路线逻辑都要用，
 * 改成全局（名字没变，免得改一堆调用点）。 */
extern u8 dir;

/* 等四个电机到位（judge_wait 的有界版本）。返回 1 = 都到位 */
u8 wait_motors(void);

/* 从 (x0,y0) 走到 (x1,y1)：先按朝向对齐，再直走。只能走正交方向。
 * 返回 1 = 走到并到位，0 = 方向非法或电机没到位 */
u8 translation(u16 x0, u16 y0, u16 x1, u16 y1);

/* 陀螺仪闭环旋转自检：从当前角度转 target_delta（0.01°）再转回来。
 * 返回 1 = 两次都到位 */
u8 gyro_turn_pos_test(int32_t target_delta);

/* 从当前点走到目标点（内部调 path_planner 规划 + translation 执行）。
 * 返回 1 = 到达 */
u8 go_to(u16 *cx, u16 *cy, u16 tx, u16 ty);

#endif /* __MOTION_H */
